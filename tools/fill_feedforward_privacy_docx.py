def paragraph_text(paragraph: ET.Element) -> str:
    return "".join(text.text or "" for text in paragraph.findall(".//w:t", NS))


def set_paragraph_text(paragraph: ET.Element, value: str) -> None:
    text_nodes = paragraph.findall(".//w:t", NS)
    if not text_nodes:
        return
    text_nodes[0].text = value
    text_nodes[0].set(f"{{{XML_NS}}}space", "preserve")
    for node in text_nodes[1:]:
        node.text = ""

    for run_properties in paragraph.findall(".//w:rPr", NS):
        for child in list(run_properties):
            if child.tag == f"{{{W_NS}}}highlight":
                run_properties.remove(child)


def replace_text(value: str) -> str:
    if value in PARAGRAPH_REPLACEMENTS:
        return PARAGRAPH_REPLACEMENTS[value]
    next_value = value
    for old, new in PLACEHOLDER_REPLACEMENTS.items():
        next_value = next_value.replace(old, new)
    for old, new in TEXT_REPLACEMENTS.items():
        next_value = next_value.replace(old, new)
    return next_value


def patch_document_xml(xml_bytes: bytes) -> bytes:
    root = ET.fromstring(xml_bytes)
    changed = False
    for paragraph in root.findall(".//w:p", NS):
        current = paragraph_text(paragraph)
        updated = replace_text(current)
        if updated != current:
            set_paragraph_text(paragraph, updated)
            changed = True
    if not changed:
        return xml_bytes
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("Usage: fill_feedforward_privacy_docx.py input.docx output.docx")
    source = Path(sys.argv[1])
    output = Path(sys.argv[2])
    if output.exists():
        output.unlink()

    with zipfile.ZipFile(source, "r") as zin, zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename == "word/document.xml":
                data = patch_document_xml(data)
            zout.writestr(item, data)


if __name__ == "__main__":
    main()
